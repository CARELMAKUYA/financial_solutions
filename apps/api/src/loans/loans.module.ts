import { Body, Controller, Get, HttpCode, Module, Param, ParseUUIDPipe, Post, Query, Res } from '@nestjs/common';
import { PaymentMethod } from '@prisma/client';
import { Type } from 'class-transformer';
import { IsBoolean, IsEnum, IsInt, IsOptional, IsString, IsUUID, Max, MaxLength, Min, MinLength } from 'class-validator';
import type { Response } from 'express';
import { AuthorisedForCorrections, AuthUser, CurrentUser, OwnerOnly } from '../common/decorators';
import { IsDateOnly } from '../common/util';
import { PdfService } from '../documents/pdf.service';
import { PaymentsService } from '../payments/payments.service';
import { SettingsModule } from '../settings/settings.module';
import { LedgerService } from './ledger.service';
import { ArrangementDto, CreateLoanDto, FollowUpDto, LoanAdjustmentDto, QuoteDto, ReasonDto } from './loans.dto';
import { LoansService } from './loans.service';

class PreviewPaymentDto {
  @IsInt() @Min(1, { message: 'Enter the amount received' }) @Max(100_000_000) amountCents: number;
  @IsDateOnly() paymentDate: string;
  @IsEnum(PaymentMethod) method: PaymentMethod;
  @IsOptional() @IsBoolean() requireVerification?: boolean;
}

class RecordPaymentDto extends PreviewPaymentDto {
  @IsOptional() @IsString() @MaxLength(100) reference?: string;
  @IsOptional() @IsString() @MaxLength(1000) notes?: string;
  /** Generated by the form when it opens; makes double submissions harmless. */
  @IsUUID() idempotencyKey: string;
  @IsOptional() @IsBoolean() confirmDuplicate?: boolean;
}

export class CorrectPaymentDto {
  @IsInt() @Min(1) @Max(100_000_000) amountCents: number;
  @IsDateOnly() paymentDate: string;
  @IsEnum(PaymentMethod) method: PaymentMethod;
  @IsOptional() @IsString() @MaxLength(100) reference?: string;
  @IsOptional() @IsString() @MaxLength(1000) notes?: string;
  @IsString() @MinLength(5, { message: 'Give a reason (at least 5 characters)' }) @MaxLength(1000) reason: string;
}

class LoanListQuery {
  @IsOptional() @IsString() status?: string;
  @IsOptional() @IsString() search?: string;
  @IsOptional() @IsUUID() clientId?: string;
  @IsOptional() @Type(() => String) @IsString() arrears?: string;
}

export function sendPdf(res: Response, file: { fileName: string; pdf: Buffer }, inline = true) {
  res.setHeader('Content-Type', 'application/pdf');
  res.setHeader('Content-Disposition', `${inline ? 'inline' : 'attachment'}; filename="${file.fileName}"`);
  res.setHeader('Cache-Control', 'no-store');
  res.end(file.pdf);
}

@Controller('loans')
class LoansController {
  constructor(
    private readonly loans: LoansService,
    private readonly payments: PaymentsService,
    private readonly pdf: PdfService,
  ) {}

  /** Loan calculator: the same schedule the system will use if the loan is issued. */
  @Post('quote')
  @HttpCode(200)
  quote(@Body() dto: QuoteDto) {
    return this.loans.quote(dto);
  }

  @Post()
  create(@Body() dto: CreateLoanDto, @CurrentUser() user: AuthUser) {
    return this.loans.create(dto, user);
  }

  @Get()
  list(@Query() q: LoanListQuery) {
    return this.loans.list({ ...q, arrears: q.arrears === 'true' });
  }

  @Get(':id')
  detail(@Param('id', ParseUUIDPipe) id: string) {
    return this.loans.detail(id);
  }

  @Post(':id/payments/preview')
  @HttpCode(200)
  previewPayment(@Param('id', ParseUUIDPipe) id: string, @Body() dto: PreviewPaymentDto) {
    return this.payments.preview(id, dto);
  }

  @Post(':id/payments')
  recordPayment(@Param('id', ParseUUIDPipe) id: string, @Body() dto: RecordPaymentDto, @CurrentUser() user: AuthUser) {
    return this.payments.record(id, dto, user);
  }

  @Post(':id/arrangements/preview')
  @HttpCode(200)
  previewArrangement(@Param('id', ParseUUIDPipe) id: string, @Body() dto: ArrangementDto) {
    return this.loans.previewArrangement(id, dto);
  }

  @AuthorisedForCorrections()
  @Post(':id/arrangements')
  createArrangement(@Param('id', ParseUUIDPipe) id: string, @Body() dto: ArrangementDto, @CurrentUser() user: AuthUser) {
    return this.loans.createArrangement(id, dto, user);
  }

  @AuthorisedForCorrections()
  @Post(':id/adjustments')
  addAdjustment(@Param('id', ParseUUIDPipe) id: string, @Body() dto: LoanAdjustmentDto, @CurrentUser() user: AuthUser) {
    return this.loans.addAdjustment(id, dto, user);
  }

  @AuthorisedForCorrections()
  @Post(':id/adjustments/:adjustmentId/reverse')
  @HttpCode(200)
  reverseAdjustment(
    @Param('id', ParseUUIDPipe) id: string,
    @Param('adjustmentId', ParseUUIDPipe) adjustmentId: string,
    @Body() dto: ReasonDto,
    @CurrentUser() user: AuthUser,
  ) {
    return this.loans.reverseAdjustment(id, adjustmentId, dto.reason, user);
  }

  @OwnerOnly()
  @Post(':id/cancel')
  @HttpCode(200)
  cancel(@Param('id', ParseUUIDPipe) id: string, @Body() dto: ReasonDto, @CurrentUser() user: AuthUser) {
    return this.loans.cancel(id, dto.reason, user);
  }

  @Post(':id/follow-ups')
  followUp(@Param('id', ParseUUIDPipe) id: string, @Body() dto: FollowUpDto, @CurrentUser() user: AuthUser) {
    return this.loans.addFollowUp(id, dto, user);
  }

  @Get(':id/statement.pdf')
  async statement(@Param('id', ParseUUIDPipe) id: string, @Res() res: Response) {
    sendPdf(res, await this.pdf.statement(id));
  }

  @Get(':id/settlement-letter.pdf')
  async settlement(@Param('id', ParseUUIDPipe) id: string, @Res() res: Response) {
    sendPdf(res, await this.pdf.settlementLetter(id));
  }
}

@Module({
  imports: [SettingsModule],
  providers: [LoansService, LedgerService, PaymentsService, PdfService],
  controllers: [LoansController],
  exports: [LedgerService, PaymentsService, PdfService, LoansService],
})
export class LoansModule {}
